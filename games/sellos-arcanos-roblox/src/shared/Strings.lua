function S.get(key, lang, vars)
	local e = S.T[key]
	local str = e and (e[lang] or e.es) or key
	if vars then
		for k, v in pairs(vars) do
			str = string.gsub(str, "{" .. k .. "}", tostring(v))
		end
	end
	return str
end

return S
